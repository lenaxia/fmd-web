#!/usr/bin/env bash
# build.sh — build the FPC ground-truth capture harness (corpus/harness).
#
# 1. Ensures vendor/ holds the pinned internettools + FLRE sources
#    (fetch-vendor.sh; commits recorded in corpus/meta.json).
# 2. Ensures the pinned FPC (3.2.2) is available: uses `fpc` from PATH if
#    it reports 3.2.2, otherwise installs the official binary tarball into
#    $FPC_PREFIX (default $HOME/fpc-3.2.2) — no root required.
# 3. Regenerates pins.inc from corpus/meta.json (bakes the commit pins into
#    the binary's emitted triples).
# 4. Compiles fmd_capture.pas → bin/fmd_capture with -FcUTF8 (raw UTF-8
#    strings, no LCL units).
#
# Environment overrides:
#   FPC_PREFIX   install prefix for the pinned FPC (default ~/fpc-3.2.2)
#   FPC          explicit fpc binary to use instead of PATH lookup
set -euo pipefail

HARNESS_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
META="$HARNESS_DIR/../meta.json"
cd "$HARNESS_DIR"

IT_COMMIT="$(jq -r '.pins.internettools.commit' "$META")"
FLRE_COMMIT="$(jq -r '.pins.flre.commit' "$META")"
FPC_VERSION="$(jq -r '.pins.fpc.version' "$META")"
FPC_TARBALL="$(jq -r '.pins.fpc.tarball' "$META")"
FPC_PREFIX="${FPC_PREFIX:-$HOME/fpc-$FPC_VERSION}"

# --- 1. vendor sources -----------------------------------------------------
bash "$HARNESS_DIR/fetch-vendor.sh"

# --- 2. toolchain ----------------------------------------------------------
FPC_BIN="${FPC:-}"
if [ -z "$FPC_BIN" ]; then
  if command -v fpc >/dev/null 2>&1 && [ "$(fpc -iV 2>/dev/null)" = "$FPC_VERSION" ]; then
    FPC_BIN="$(command -v fpc)"
  else
    if [ ! -x "$FPC_PREFIX/bin/fpc" ]; then
      echo "build: installing FPC $FPC_VERSION into $FPC_PREFIX (no root needed)"
      TMP="$(mktemp -d)"
      trap 'rm -rf "$TMP"' EXIT
      curl -sSL -o "$TMP/fpc.tar" "$FPC_TARBALL"
      tar -xf "$TMP/fpc.tar" -C "$TMP"
      # installer prompts: prefix, docs, demos, cfg-substitution
      printf '%s\nn\nn\ny\n' "$FPC_PREFIX" | bash "$TMP"/fpc-*.*/install.sh >/dev/null
    fi
    FPC_BIN="$FPC_PREFIX/bin/fpc"
  fi
fi
echo "build: using $($FPC_BIN -iV) fpc at $FPC_BIN"
ACTUAL="$("$FPC_BIN" -iV)"
if [ "$ACTUAL" != "$FPC_VERSION" ]; then
  echo "build: FATAL fpc reports $ACTUAL, pin requires $FPC_VERSION" >&2
  exit 1
fi

# --- 3. pins.inc -----------------------------------------------------------
cat > pins.inc <<EOF
// GENERATED by build.sh — do not edit by hand.
// Values come from corpus/meta.json ("pins").
const
  InternetToolsCommit = '$IT_COMMIT';
  FLRECommit = '$FLRE_COMMIT';
EOF

# vendor hygiene: keep the pinned source trees pristine — unit output goes
# to bin/ (-FUbin), and any stray artifacts are purged before compiling
find vendor -type f \( -name '*.ppu' -o -name '*.o' -o -name '*.rsj' \) -delete

# --- 4. compile ------------------------------------------------------------
mkdir -p bin
LOG="$(mktemp)"
if ! "$FPC_BIN" -B -O2 -FcUTF8 -obin/fmd_capture -FUbin \
  -Fuvendor/internettools/data \
  -Fuvendor/internettools/internet \
  -Fuvendor/FLRE/src \
  fmd_capture.pas > "$LOG" 2>&1; then
  cat "$LOG" >&2
  rm -f "$LOG"
  echo "build: FATAL compile failed" >&2
  exit 1
fi
rm -f "$LOG"

if [ ! -x bin/fmd_capture ]; then
  echo "build: FATAL compile failed" >&2
  exit 1
fi

echo "build: running selftest gate"
./bin/fmd_capture selftest

echo "build: OK — bin/fmd_capture ready (internettools@$IT_COMMIT flre@$FLRE_COMMIT fpc@$FPC_VERSION)"
