/**
 * User-visible string jargon gate (UX audit D-1 + the app-wide sweep):
 * internal spec/ticket ids must NEVER render to users. The audit found
 * "(D19)" inside a Downloads aria-live line, "(D20)" in the bootstrap
 * banner, "(§5.11)" in proxy tooltips, "§5.1" in the options editor
 * legend and "FMD2 parity:"/"frmNewChapter parity:" prefixes in
 * overlay copy — machine vocabulary users cannot parse (and screen
 * readers read aloud).
 *
 * HOW this gate finds only USER-VISIBLE text: it walks the real
 * TypeScript AST of web/src and collects exactly the surfaces a user
 * can read —
 *   - string literals and template-literal spans (JSX attribute
 *     values, title/aria/placeholder props, toasts, all quoted copy);
 *   - JSX text nodes (the prose between tags).
 * Comments are SYNTAX TRIVIA in the AST, so the deliberate in-code
 * documentation of these same ids (D19/D20/§5.11 references in
 * comments, tests, docs) is invisible to the scan by construction —
 * exactly the split the audit mandates: keep the ids in comments and
 * tests, never in rendered strings. Regex literals and identifiers are
 * never string-literal nodes, so they cannot false-positive either.
 *
 * Generated API documentation (src/api/openapi.d.ts — server-owned
 * OpenAPI descriptions, regenerated by contract tooling) is excluded:
 * it is not app UI, and its §-references document the parity lineage
 * of each endpoint for API consumers.
 */
import { readdirSync, readFileSync, statSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import ts from 'typescript';
import { describe, expect, it } from 'vitest';

const srcRoot: string = fileURLToPath(new URL('../src', import.meta.url));

/** Recursively collect web/src source files (*.ts/*.tsx, not *.d.ts). */
function sourceFiles(dir: string): string[] {
  const out: string[] = [];
  for (const entry of readdirSync(dir)) {
    const full: string = join(dir, entry);
    if (statSync(full).isDirectory()) {
      out.push(...sourceFiles(full));
    } else if ((entry.endsWith('.ts') || entry.endsWith('.tsx')) && !entry.endsWith('.d.ts')) {
      out.push(full);
    }
  }
  return out;
}

/** One piece of user-readable text with its provenance. */
interface VisibleText {
  readonly file: string;
  readonly line: number;
  readonly text: string;
  readonly kind: 'string' | 'jsx-text';
}

/** AST walk: every string literal/template span + JSX text node. */
function visibleTexts(file: string): VisibleText[] {
  const source: string = readFileSync(file, 'utf8');
  const sf: ts.SourceFile = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, file.endsWith('.tsx') ? ts.ScriptKind.TSX : ts.ScriptKind.TS);
  const found: VisibleText[] = [];
  const visit = (node: ts.Node): void => {
    if (ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)) {
      found.push({ file, line: sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1, text: node.text, kind: 'string' });
    } else if (
      ts.isTemplateHead(node) ||
      ts.isTemplateMiddle(node) ||
      ts.isTemplateTail(node)
    ) {
      found.push({ file, line: sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1, text: node.text, kind: 'string' });
    } else if (node.kind === ts.SyntaxKind.JsxText) {
      found.push({ file, line: sf.getLineAndCharacterOfPosition(node.getStart(sf)).line + 1, text: node.getText(sf), kind: 'jsx-text' });
    }
    node.forEachChild(visit);
  };
  visit(sf);
  return found;
}

/** The forbidden internal-vocabulary patterns (audit D-1 family). */
const PATTERNS: readonly { readonly id: string; readonly re: RegExp; readonly why: string }[] = [
  { id: 'ticket-id', re: /\(\s*D\d+\s*\)/, why: 'internal ticket id in parens, e.g. "(D19)"' },
  { id: 'bare-ticket-id', re: /\bD\d{1,2}\b/, why: 'internal ticket id, e.g. D19' },
  { id: 'spec-section', re: /§\s*\d+(\.\d+)?/, why: 'internal spec section reference, e.g. "§5.11"' },
  { id: 'fmd2-form-name', re: /\bfrm[A-Z]\w*/, why: 'FMD2 Delphi form name, e.g. frmNewChapter' },
  { id: 'parity-prefix', re: /\bFMD2 parity\s*:/i, why: 'internal parity vocabulary prefix in user copy' },
];

describe('user-visible string jargon gate (D-1)', (): void => {
  it('web/src renders no internal spec/ticket ids or parity jargon', (): void => {
    const violations: string[] = [];
    for (const file of sourceFiles(srcRoot)) {
      for (const visible of visibleTexts(file)) {
        for (const pattern of PATTERNS) {
          if (pattern.re.test(visible.text)) {
            violations.push(
              `${visible.file.replace(srcRoot, 'src')}:${String(visible.line)} [${pattern.id}] ${pattern.why}: ${JSON.stringify(visible.text.trim().slice(0, 90))}`,
            );
          }
        }
      }
    }
    expect(violations, `internal ids leaked into user-visible strings:\n${violations.join('\n')}\n — strip the id from the string (keep it in a comment or test); see docs/UX-AUDIT.md D-1.`).toEqual([]);
  });

  it('the gate scans the expected surface (a non-empty, multi-directory web/src)', (): void => {
    const files: string[] = sourceFiles(srcRoot);
    expect(files.length).toBeGreaterThan(20);
    expect(files.some((f): boolean => f.endsWith('pages/MangaPage.tsx'))).toBe(true);
    // Sanity: the AST extraction really sees JSX text (the richest
    // historical leak surface) and string literals in every file.
    const mangaTexts: readonly VisibleText[] = visibleTexts(files.find((f): boolean => f.endsWith('MangaPage.tsx'))!);
    expect(mangaTexts.some((t): boolean => t.kind === 'jsx-text')).toBe(true);
    expect(mangaTexts.some((t): boolean => t.kind === 'string')).toBe(true);
  });
});
